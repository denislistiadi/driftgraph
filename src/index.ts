import * as core from '@actions/core';
import * as github from '@actions/github';
import * as exec from '@actions/exec';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { scanArchitecture } from './scanner';
import { evaluateRules, RuleViolation } from './rules';
import { diffGraphs } from './differ';
import { generateMermaid } from './mermaid';
import { parseRulesSource, readRulesFile, resolveRulesPath } from './config';

const COMMENT_MARKER = '<!-- driftgraph-report -->';
const MAX_ANNOTATIONS = 20;

type Octokit = ReturnType<typeof github.getOctokit>;

function getErrorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

function getErrorStatus(error: unknown): number | undefined {
  if (typeof error === 'object' && error !== null && 'status' in error) {
    const status = (error as { status?: unknown }).status;
    if (typeof status === 'number') {
      return status;
    }
  }
  return undefined;
}

async function prepareBaseWorktree(baseDir: string, baseSha: string, baseRef: string): Promise<void> {
  try {
    await exec.exec('git', ['fetch', 'origin', baseSha]);
    await exec.exec('git', ['worktree', 'add', '--detach', baseDir, baseSha]);
  } catch (error) {
    core.warning(`Could not fetch base SHA ${baseSha}; retrying with ${baseRef}. ${getErrorMessage(error)}`);
    fs.rmSync(baseDir, { recursive: true, force: true });
    await exec.exec('git', ['worktree', 'prune'], { ignoreReturnCode: true, silent: true });
    await exec.exec('git', ['fetch', 'origin', baseRef]);
    await exec.exec('git', ['worktree', 'add', '--detach', baseDir, 'FETCH_HEAD']);
  }
}

async function cleanupWorktree(baseDir: string | undefined, tempRoot: string | undefined): Promise<void> {
  if (baseDir) {
    try {
      await exec.exec('git', ['worktree', 'remove', '--force', baseDir], {
        ignoreReturnCode: true,
        silent: true,
      });
    } catch (error) {
      core.warning(`Failed to remove the base worktree: ${getErrorMessage(error)}`);
    }
  }

  if (tempRoot) {
    try {
      fs.rmSync(tempRoot, { recursive: true, force: true });
    } catch (error) {
      core.warning(`Failed to remove the temporary directory: ${getErrorMessage(error)}`);
    }
  }

  if (baseDir) {
    await exec.exec('git', ['worktree', 'prune'], {
      ignoreReturnCode: true,
      silent: true,
    });
  }
}

function buildCommentBody(mermaidDiagram: string, violations: RuleViolation[]): string {
  const violationSection = violations.length > 0
    ? [
        '',
        `> **Architecture Violations Detected (${violations.length})**`,
        '> Please check the highlighted red edges in the diagram and the workflow annotations.',
        '',
        ...violations.slice(0, 10).map(
          violation => `- \`${violation.edge.source}\` -> \`${violation.edge.target}\` (${violation.ruleName})`
        ),
        ...(violations.length > 10 ? [`- ...and ${violations.length - 10} more.`] : []),
      ].join('\n')
    : '> No architecture violations detected.';

  return `${COMMENT_MARKER}
## Driftgraph Architecture Report

Here is the visual diff of the architectural changes in this PR:

\`\`\`mermaid
${mermaidDiagram}
\`\`\`

${violationSection}

*Generated by [Driftgraph](https://github.com/denislistiadi/driftgraph).*`;
}

async function upsertComment(
  octokit: Octokit,
  owner: string,
  repo: string,
  issueNumber: number,
  body: string,
): Promise<void> {
  try {
    const comments = await octokit.paginate(octokit.rest.issues.listComments, {
      owner,
      repo,
      issue_number: issueNumber,
      per_page: 100,
    }) as Array<{ id: number; body?: string | null }>;

    const existingComment = comments.find(comment =>
      comment.body?.includes(COMMENT_MARKER) ||
      comment.body?.includes('Driftgraph Architecture Report')
    );

    if (existingComment) {
      core.info('Updating existing comment...');
      await octokit.rest.issues.updateComment({
        owner,
        repo,
        comment_id: existingComment.id,
        body,
      });
    } else {
      core.info('Creating new comment...');
      await octokit.rest.issues.createComment({
        owner,
        repo,
        issue_number: issueNumber,
        body,
      });
    }
  } catch (error) {
    const status = getErrorStatus(error);
    if (status === 403 || status === 404) {
      core.warning(
        `Unable to write the Driftgraph comment (HTTP ${status}). ` +
        'This is expected for pull requests from forks because the token is read-only. ' +
        'Architecture violations are still reported as workflow annotations.'
      );
    } else {
      core.warning(`Failed to post the Driftgraph comment: ${getErrorMessage(error)}`);
    }
  }
}

function annotateViolations(violations: RuleViolation[]): void {
  for (const violation of violations.slice(0, MAX_ANNOTATIONS)) {
    core.error(`[${violation.ruleName}] ${violation.edge.source} -> ${violation.edge.target}`, {
      title: 'Driftgraph architecture violation',
      file: violation.edge.source,
      startLine: 1,
      endLine: 1,
    });
  }

  if (violations.length > MAX_ANNOTATIONS) {
    core.warning(
      `Showing the first ${MAX_ANNOTATIONS} architecture violations as annotations. ` +
      `${violations.length - MAX_ANNOTATIONS} more are listed in the Driftgraph comment when available.`
    );
  }
}

async function run(): Promise<void> {
  let tempRoot: string | undefined;
  let baseDir: string | undefined;

  try {
    const context = github.context;

    if (context.eventName !== 'pull_request') {
      core.info('Not a pull request event. Skipping Driftgraph.');
      return;
    }

    const token = core.getInput('github-token', { required: true });
    const rulesFile = core.getInput('rules-file') || '.driftgraph.yml';
    const rulesSource = parseRulesSource(core.getInput('rules-source') || 'base');

    const octokit = github.getOctokit(token);
    const pr = context.payload.pull_request;
    if (!pr) {
      throw new Error('Pull request payload is missing');
    }

    const baseSha = pr.base.sha;
    const baseRef = pr.base.ref;
    const headDir = process.cwd();

    core.info(`Base ref: ${baseRef}, SHA: ${baseSha}`);

    tempRoot = fs.mkdtempSync(path.join(process.env.RUNNER_TEMP || os.tmpdir(), 'driftgraph-'));
    baseDir = path.join(tempRoot, 'base');

    core.info(`Checking out base branch into ${baseDir}...`);
    await prepareBaseWorktree(baseDir, baseSha, baseRef);

    const resolvedRules = resolveRulesPath({
      baseDir,
      headDir,
      rulesFile,
      rulesSource,
    });

    if (resolvedRules.usedHeadFallback) {
      core.warning(
        `No rules file found on the base branch. Using the rules file from the PR head: ${resolvedRules.path}`
      );
    }

    if (!resolvedRules.exists) {
      core.info(`No rules file found at ${resolvedRules.path}. Gatekeeping skipped.`);
    } else {
      core.info(`Using rules file at ${resolvedRules.path}`);
    }

    const rules = readRulesFile(resolvedRules.path);

    const tsconfigBase = fs.existsSync(path.join(baseDir, 'tsconfig.json'))
      ? path.join(baseDir, 'tsconfig.json')
      : undefined;
    const tsconfigHead = fs.existsSync(path.join(headDir, 'tsconfig.json'))
      ? path.join(headDir, 'tsconfig.json')
      : undefined;

    core.info('Scanning base architecture...');
    const baseGraph = scanArchitecture(baseDir, tsconfigBase);

    core.info('Scanning head architecture...');
    const headGraph = scanArchitecture(headDir, tsconfigHead);

    core.info('Evaluating architecture rules...');
    const violations = evaluateRules(headGraph, rules);

    core.info('Diffing graphs...');
    const diff = diffGraphs(baseGraph, headGraph, violations);

    core.info('Generating Mermaid.js diagram...');
    const mermaidDiagram = generateMermaid(diff);
    const commentBody = buildCommentBody(mermaidDiagram, violations);

    const { owner, repo } = context.repo;
    const issueNumber = pr.number;

    core.info('Updating PR comment...');
    await upsertComment(octokit, owner, repo, issueNumber, commentBody);

    annotateViolations(violations);

    if (violations.length > 0) {
      core.setFailed(`Architecture rules violated! ${violations.length} forbidden dependencies found.`);
    }
  } catch (error) {
    if (error instanceof Error && error.stack) {
      core.debug(error.stack);
    }
    core.setFailed(getErrorMessage(error));
  } finally {
    await cleanupWorktree(baseDir, tempRoot);
  }
}

void run();
